#!/usr/bin/env node
/* JSON is the source of truth. Rebuild without npm packages or a server. */
'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const names=['config','dashboard','reports','logs','modules','navigation'];
const data=Object.fromEntries(names.map(name=>[name,JSON.parse(fs.readFileSync(path.join(root,'data',name+'.json'),'utf8').replace(/^\uFEFF/,''))]));
if(data.config.format!=='nt-wifi-offline-config'||data.config.schemaVersion!==1)throw Error('Unsupported config format');
const content='/* Generated from data/*.json. Do not edit this file by hand. */\nwindow.NT_DATA = '+JSON.stringify(data,null,2)+';\n';
fs.writeFileSync(path.join(root,'js','offline-data.js'),content,'utf8');
console.log('Updated js/offline-data.js from '+names.length+' JSON files.');
